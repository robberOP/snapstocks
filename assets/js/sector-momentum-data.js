/* Loads the live sector-momentum feed for the Momentum Chart / Momentum Table
   pages. Shape documented in /data/sector_momentum.sample.json; the real feed at
   /data/sector_momentum.json is generated by `srp report site-export` in the
   stock-research pipeline (execution/sector_momentum/site_export.py) from
   sector_momentum_daily — see snapstocks/DESIGN.md and that repo's
   reports/sector_momentum/README.md.

   Exposes window.loadSectorMomentum() -> Promise<data>, where `data` is
   { as_of, periods, unmapped_label, sector: [...], industry: [...] } — each row
   is { name, n_mapped, n_with_data, breadth: {1d,1w}, ret: {1d,2d,1w,1m,3m},
   vol_ratio: {1d,2d,1w,1m,3m} }. */
(function (global) {
  global.loadSectorMomentum = function () {
    return fetch("/data/sector_momentum.json")
      .then(function (res) {
        if (!res.ok) throw new Error("sector_momentum.json: HTTP " + res.status);
        return res.json();
      });
  };
})(window);
