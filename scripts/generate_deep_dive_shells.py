#!/usr/bin/env python3
"""Stamps out SnapStocks shell pages for deep-dive reports.

Deep-dive reports (stock-analysis/deep-dive/reports/*.html) are raw,
self-contained HTML documents generated by a separate AI/tool — each one
has its own <style> block and design tokens, so it can't be pasted into a
SnapStocks page directly without leaking styles into the site's own chrome.
Instead each report gets a thin shell page (topnav/breadcrumbs/subnav, same
as every other page) that iframes it. See DESIGN.md section 9 for the why.

Workflow: drop a new report's HTML file into
stock-analysis/deep-dive/reports/, then run this script. It stamps out a
shell for any report that doesn't have one yet (existing shells are never
overwritten unless you pass --force) and rewrites
data/deep_dive_reports.json, the manifest stock-analysis/index.html renders
its report listing from.

Usage:
    python scripts/generate_deep_dive_shells.py [--force] [--dry-run]
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPORTS_DIR = ROOT / "stock-analysis" / "deep-dive" / "reports"
SHELL_DIR = ROOT / "stock-analysis" / "deep-dive"
MANIFEST_PATH = ROOT / "data" / "deep_dive_reports.json"

H1_RE = re.compile(r"<h1[^>]*>(.*?)</h1>", re.IGNORECASE | re.DOTALL)
TAG_RE = re.compile(r"<[^>]+>")
WS_RE = re.compile(r"\s+")

