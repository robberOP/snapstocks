def slugify(stem: str) -> str:
    slug = stem.strip().lower()
    slug = re.sub(r"[^a-z0-9]+", "-", slug)
    return slug.strip("-")


def extract_company_name(html_text: str, fallback: str) -> str:
    """Pulls the display name from the report's first <h1>.

    <h1> has been the reliable field across every report seen so far — a
    report's own <title> is not (e.g. one report's <title> says "Zaggle
    Ledger" while its <h1> says "Zaggle Prepaid Ocean Services").
    """
    match = H1_RE.search(html_text)
    if not match:
        return fallback
    name = TAG_RE.sub("", match.group(1))
    name = WS_RE.sub(" ", name).strip()
    return name or fallback


def humanize_stem(stem: str) -> str:
    words = re.split(r"[-_]+", stem.strip())
    return " ".join(w.capitalize() if w.islower() or w.isupper() else w for w in words if w)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--force", action="store_true", help="overwrite existing shell files")
    parser.add_argument("--dry-run", action="store_true", help="print what would happen, write nothing")
    args = parser.parse_args()

    if not REPORTS_DIR.exists():
        raise SystemExit(f"No reports directory at {REPORTS_DIR}")

    manifest: list[dict[str, str]] = []
    created: list[Path] = []
    skipped: list[Path] = []
    seen_slugs: dict[str, Path] = {}

    for report_path in sorted(REPORTS_DIR.glob("*.html")):
        stem = report_path.stem
        slug = slugify(stem)
        if not slug:
            print(f"warning: {report_path.name} has no usable slug, skipping")
            continue
        if slug in seen_slugs:
            print(f"warning: {report_path.name} slugifies to '{slug}', same as {seen_slugs[slug].name} - skipping")
            continue
        seen_slugs[slug] = report_path

        name = extract_company_name(report_path.read_text(encoding="utf-8"), fallback=humanize_stem(stem))
        shell_path = SHELL_DIR / f"{slug}.html"
        shell_url = f"/stock-analysis/deep-dive/{slug}.html"
        report_url = f"/stock-analysis/deep-dive/reports/{report_path.name}"

        manifest.append({"slug": slug, "name": name, "shell_url": shell_url, "report_url": report_url})

        if shell_path.exists() and not args.force:
            skipped.append(shell_path)
            continue

        if not args.dry_run:
            shell_path.write_text(
                SHELL_TEMPLATE.format(name=name, shell_url=shell_url, report_url=report_url),
                encoding="utf-8",
                newline="\n",
            )
        created.append(shell_path)

    manifest.sort(key=lambda r: r["name"])

    if not args.dry_run:
        MANIFEST_PATH.parent.mkdir(parents=True, exist_ok=True)
        MANIFEST_PATH.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    prefix = "[dry-run] would create" if args.dry_run else "created "
    for p in created:
        print(f"{prefix} {p.relative_to(ROOT).as_posix()}")
    for p in skipped:
        print(f"skipped  {p.relative_to(ROOT).as_posix()} (already exists - use --force to overwrite)")
    manifest_note = "[dry-run] would write" if args.dry_run else "wrote   "
    print(f"{manifest_note} {MANIFEST_PATH.relative_to(ROOT).as_posix()} ({len(manifest)} reports)")


if __name__ == "__main__":
    main()
